#!/usr/bin/env python3
"""Checks the answers of the no-comments fan-out (.claude/skills/no-comments/SKILL.md).

A cheap sorter (one per file) answers one JSON line per comment it judged:
  {"file": "...", "line": 12, "end": 14, "comment": "<its first line, exact>",
   "code": "<a line of code it judged it against, exact>",
   "verdict": "delete" | "keep" | "review", "why": "<the rule, a few words>"}
Nobody reads twenty answers to trust them, so this does:
- a row whose comment is not on its line, or whose code is not near it, is dropped,
  and its file is to be sorted again;
- a comment the change added that no kept row covers is missing, and its file too;
- a deletion of a line that is always kept (a Guard file marker, a generated header,
  a link to the specs, the design or the owner's feedback, a licence) becomes a keep,
  and a deletion of a lint suppression becomes a review: removing one changes the code.
- the same words in one change get one verdict, the most careful one given (keep, then
  review, then delete);
- a sorter's "delete" is only a proposal: it is applied only when code proves the comment
  says nothing (tool/empty_comments.py); else it is listed as proposed, for the builder.
Then it prints the counts, five applied deletions to check against the code, the proposed
and the review lists. It fails (exit 1) while anything is to be sorted again.

--files lists what to fan out: each changed file with the comments the change added,
generated files left out. --apply deletes the applied rows (working tree only). The change is the working tree against the main it was built on
(tool/change_base.py), or --range A..B for commits.

usage: tool/comment_rows.py --files [--range A..B | --base REF] [-- paths...]
       tool/comment_rows.py [--range A..B | --base REF] [--apply] answers... [-- paths...]
"""

import json
import random
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from change_base import change_base
from empty_comments import comment_text, normal, provably_empty

ROOT = Path(__file__).resolve().parents[1]
VERDICTS = ("delete", "keep", "review")
CAREFUL = {"delete": 0, "review": 1, "keep": 2}
SHOWN = ("applied", "proposed", "keep", "review")
HASH = {".py", ".sh", ".toml", ".yml", ".yaml", ".cfg"}
SLASH = {".dart", ".js", ".mjs", ".cjs", ".ts", ".kt", ".swift", ".java", ".tla"}
GENERATED_NAME = re.compile(r"\.(g|freezed|mocks|gr)\.dart$|^contract_samples/")
GENERATED_HEAD = re.compile(r"GENERATED|Generated by|DO NOT (EDIT|MODIFY)", re.I)
ALWAYS_KEEP = [
    (re.compile(r"Guard file"), "a Guard file marker (tool/guard_edits.py reads it)"),
    (GENERATED_HEAD, "a generated-file header"),
    (re.compile(r"docs/(specs|design)/|owner-feedback\.md"), "a link to the specs"),
    (re.compile(r"licen[cs]e|copyright|SPDX", re.I), "a licence line"),
]
SUPPRESSION = re.compile(r"noqa|type: ?ignore|// ?ignore(_for_file)?:|pragma|pylint:")
WINDOW = (
    3,
    8,
)  # lines before the comment, and after it and the comments that follow it


def git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(ROOT), *args], capture_output=True, text=True
    ).stdout


class Change:
    """The files a change touched, their text at its head, the lines it added."""

    def __init__(self, span: str | None, paths: list[str] | None = None, base=None):
        if span:
            self.base, self.head = span.split("..", 1)
        else:
            self.base, self.head = base or change_base(ROOT) or "origin/main", None
        ends = [self.base] + ([self.head] if self.head else [])
        only = ["--", *paths] if paths else []
        names = git("diff", "--name-only", "--diff-filter=AM", *ends, *only).split()
        if not self.head:
            names += git("ls-files", "--others", "--exclude-standard", *only).split()
        self.names = sorted(set(names))
        self._text: dict[str, list[str]] = {}

    def lines(self, path: str) -> list[str]:
        if path not in self._text:
            if self.head:
                text = git("show", f"{self.head}:{path}")
            else:
                file = ROOT / path
                text = file.read_text(errors="replace") if file.is_file() else ""
            self._text[path] = text.splitlines()
        return self._text[path]

    def added(self, path: str) -> list[int]:
        ends = [self.base] + ([self.head] if self.head else [])
        diff = git("diff", "-U0", *ends, "--", path)
        if not diff:
            return list(range(1, len(self.lines(path)) + 1))
        found = []
        for m in re.finditer(r"^@@ -\S+ \+(\d+)(?:,(\d+))? @@", diff, re.M):
            start, count = int(m[1]), int(m[2] if m[2] is not None else 1)
            found += range(start, start + count)
        return found


def generated(path: str, lines: list[str]) -> bool:
    return bool(GENERATED_NAME.search(path)) or any(
        GENERATED_HEAD.search(line) for line in lines[:5]
    )


def is_comment(path: str, line: str) -> bool:
    text, ext = line.strip(), Path(path).suffix or Path(path).name
    if ext in HASH or ext == "justfile":
        if text.startswith("#") and not text.startswith("#!"):
            return True
        if ext == ".py" and text.startswith(('"""', "'''", 'r"""')):
            return True
        return bool(re.search(r"\s#\s", line)) and not re.search(r"[\"'].*\s#\s", line)
    if ext in SLASH:
        if text.startswith(("//", "/*", "* ", "*/")) or text == "*":
            return True
        return bool(re.search(r"\s//\s", line)) and not re.search(r"[\"'].*//", line)
    return False


def to_sort(change: Change) -> dict[str, list[int]]:
    """{file: the lines where the change added a comment}, generated files left out."""
    out = {}
    for path in change.names:
        lines = change.lines(path)
        if generated(path, lines):
            continue
        hits = [n for n in change.added(path) if 0 < n <= len(lines)]
        hits = [n for n in hits if is_comment(path, lines[n - 1])]
        if hits:
            out[path] = hits
    return out


def rows_in(text: str) -> list[dict]:
    rows = []
    for line in text.splitlines():
        line = line.strip().strip("`")
        if line.startswith("{"):
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                rows.append({"bad": line[:80]})
    return rows


def judge_row(row: dict, change: Change) -> str | None:
    """Why `row` cannot be trusted, or None."""
    if "bad" in row:
        return f"not JSON: {row['bad']}"
    path, verdict = row.get("file", ""), row.get("verdict")
    if path not in change.names:
        return f"{path or '(no file)'} is not a file the change touched"
    if verdict not in VERDICTS:
        return f"verdict {verdict!r} is not one of {', '.join(VERDICTS)}"
    lines, line = change.lines(path), row.get("line")
    end = row.get("end") or line
    if not isinstance(line, int) or not isinstance(end, int) or not 0 < line <= end:
        return "no line number"
    comment, code = (
        str(row.get("comment", "")).strip(),
        str(row.get("code", "")).strip(),
    )
    if not comment or line > len(lines) or comment not in lines[line - 1]:
        return f"line {line}: the comment it quotes is not on that line"
    after = (
        end  # the comments and blank lines after it do not count (a banner's docstring)
    )
    while after < len(lines) and (
        not lines[after].strip() or is_comment(path, lines[after])
    ):
        after += 1
    near = lines[max(0, line - 1 - WINDOW[0]) : after + WINDOW[1]]
    if not code or not any(code in other for other in near):
        return f"line {line}: the code it quotes is not near the comment"
    return None


def overrule(row: dict, change: Change) -> str | None:
    """A deletion this tool turns into a keep or a review (the row is changed)."""
    if row["verdict"] != "delete":
        return None
    span = change.lines(row["file"])[row["line"] - 1 : row.get("end") or row["line"]]
    for pattern, what in ALWAYS_KEEP:
        if any(pattern.search(line) for line in span):
            row["verdict"], row["why"] = "keep", what
            return f"delete -> keep: {what}"
    if any(SUPPRESSION.search(line) for line in span):
        row["verdict"], row["why"] = "review", "a lint suppression"
        return "delete -> review: a lint suppression (removing it changes the code)"
    return None


def span_text(row: dict, change: Change) -> str:
    lines = change.lines(row["file"])[row["line"] - 1 : row.get("end") or row["line"]]
    return normal(" ".join(comment_text(row["file"], line) for line in lines))


def one_verdict(rows: list[dict], change: Change) -> list[str]:
    """Rows with the same words get the most careful verdict any of them was given."""
    groups: dict[str, list[dict]] = {}
    for row in rows:
        if text := span_text(row, change):
            groups.setdefault(text, []).append(row)
    notes = []
    for same in groups.values():
        verdict = max((r["verdict"] for r in same), key=CAREFUL.get)
        for row in same:
            if row["verdict"] != verdict:
                notes.append(
                    f"one verdict: {row['file']}:{row['line']}: {row['verdict']} -> {verdict}"
                    " (the same words are judged elsewhere in the change)"
                )
                row["verdict"] = verdict
    return notes


def settle(rows: list[dict], change: Change) -> None:
    """A delete becomes applied (code proves it empty) or proposed (the builder decides)."""
    for path in {r["file"] for r in rows}:
        lines, mine = change.lines(path), [r for r in rows if r["file"] == path]
        going = {
            n
            for r in mine
            if r["verdict"] == "delete"
            for n in range(r["line"], (r.get("end") or r["line"]) + 1)
        }
        kept = {
            normal(comment_text(path, line))
            for n, line in enumerate(lines, 1)
            if n not in going and is_comment(path, line)
        }
        for row in mine:
            if row["verdict"] != "delete":
                continue
            end = row.get("end") or row["line"]
            why = provably_empty(path, lines, row["line"], end, kept)
            row["verdict"] = "applied" if why else "proposed"
            row["proof"] = why or ""


def apply(rows: list[dict], change: Change) -> list[str]:
    """Deletes whole-line `#`/`//` comment rows; returns the rows left to the caller."""
    left, gone = [], {}
    for row in rows:
        path = row["file"]
        span = range(row["line"], (row.get("end") or row["line"]) + 1)
        lines = change.lines(path)
        whole = all(lines[n - 1].strip().startswith(("#", "//")) for n in span)
        if whole and not lines[row["line"] - 1].strip().startswith("#!"):
            gone.setdefault(path, set()).update(span)
        else:
            left.append(f"{path}:{row['line']}")
    for path, numbers in gone.items():
        kept = [x for n, x in enumerate(change.lines(path), 1) if n not in numbers]
        (ROOT / path).write_text("\n".join(kept) + "\n")
    return left


def main(argv: list[str]) -> int:
    argv, paths = (
        (argv[: argv.index("--")], argv[argv.index("--") + 1 :])
        if "--" in argv
        else (argv, [])
    )
    given = {k: argv[argv.index(k) + 1] for k in ("--range", "--base") if k in argv}
    span = given.get("--range")
    change = Change(span, paths, given.get("--base"))
    wanted = to_sort(change)
    if "--files" in argv:
        for path, hits in wanted.items():
            print(f"{path}  comments added at lines {', '.join(map(str, hits))}")
        return 0
    named = [a for a in argv if not a.startswith("--") and a not in given.values()]
    rows = [r for name in named for r in rows_in(Path(name).read_text())]
    good, again, notes = [], set(), []
    for row in rows:
        why = judge_row(row, change)
        if why:
            again.add(row.get("file", "?"))
            notes.append(f"dropped: {row.get('file', '?')}: {why}")
            continue
        if note := overrule(row, change):
            notes.append(f"overruled: {row['file']}:{row['line']}: {note}")
        good.append(row)
    for path, hits in wanted.items():
        for n in hits:
            covered = any(
                r["file"] == path and r["line"] <= n <= (r.get("end") or r["line"])
                for r in good
            )
            if not covered:
                again.add(path)
                notes.append(f"missing: {path}:{n}: no row judged this comment")
    notes += one_verdict(good, change)
    settle(good, change)
    count = {v: [r for r in good if r["verdict"] == v] for v in SHOWN}
    print(", ".join(f"{v} {len(count[v])}" for v in SHOWN) + f" (rows {len(rows)})")
    for note in notes:
        print(note)
    print("Check these applied deletions against the code:")
    for r in random.Random(0).sample(count["applied"], min(5, len(count["applied"]))):
        print(f"  {r['file']}:{r['line']}  {r['comment']!r}  ({r['proof']})")
    print(
        "Proposed (the builder decides; a why goes only with a test or name that says it):"
    )
    for r in count["proposed"]:
        print(f"  {r['file']}:{r['line']}  {r['comment']!r}  {r.get('why', '')}")
    print("Review (for the builder):")
    for r in count["review"]:
        print(f"  {r['file']}:{r['line']}  {r['comment']!r}  {r.get('why', '')}")
    if "--apply" in argv and not span and not again:
        left = apply(count["applied"], change)
        print(f"Deleted {len(count['applied']) - len(left)}; delete by hand: {left}")
    if again:
        print(f"Sort again (one answer each): {', '.join(sorted(again))}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
